/** Modern name for a legacy numeric block id and data value, or null if unknown. */
export function legacyBlockName(id: number, data: number): string | null {
  const e = LEGACY[id];
  if (id === 0) return 'air';
  if (e === undefined) return null;
  if (typeof e === 'string') return e;
  // Logs and leaves keep their axis/decay bits above the wood type
  const mask = id === 17 || id === 18 || id === 161 || id === 162 ? 3 : 15;
  return e[(data & mask) % e.length] ?? e[0];
}
