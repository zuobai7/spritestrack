function mix(a: number, b: number, t: number): number {
  const ch = (s: number) => Math.round(((a >> s) & 255) * t + ((b >> s) & 255) * (1 - t));
  return (ch(16) << 16) | (ch(8) << 8) | ch(0);
}

export interface BlockColor {
  /** RGB color, or null for blocks that import as empty space. */
  color: number | null;
  /** True when the color was guessed from words in the name. */
  guessed: boolean;
}

/** The color a block id becomes, e.g. "minecraft:spruce_stairs[half=top]". */
export function blockColor(id: string): BlockColor {
  const n = baseBlockName(id);
  if (!n || EMPTY.has(n)) return { color: null, guessed: false };
  const known = lookup(n);
  if (known !== undefined) return { color: known, guessed: false };
  for (const [word, c] of KEYWORDS) if (n.includes(word)) return { color: c, guessed: true };
  return { color: UNKNOWN_COLOR, guessed: true };
}

