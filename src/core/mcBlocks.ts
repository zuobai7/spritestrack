/** Strips the namespace and block states: "minecraft:oak_stairs[facing=east]" → "oak_stairs". */
export function baseBlockName(id: string): string {
  let n = id.trim().toLowerCase();
  const bracket = n.indexOf('[');
  if (bracket >= 0) n = n.slice(0, bracket);
  const colon = n.indexOf(':');
  if (colon >= 0) n = n.slice(colon + 1);
  return n;
}

/** Color of a block that the tables know by name or by a recognizable variant of a name. */
function lookup(n: string): number | undefined {
  if (BLOCKS[n] !== undefined) return BLOCKS[n];
  // Dyed blocks: "light_blue_concrete", "red_bed", "black_candle_cake"
  for (const dye of [...DYES].sort((a, b) => b.length - a.length))
    if (n.startsWith(dye + '_')) {
      const material = n.slice(dye.length + 1);
      const table = DYED[material] ?? DYED[DYED_ALIAS[material] ?? ''];
      if (table) return table[DYES.indexOf(dye)];
    }
  if (n.startsWith('silver_')) return lookup('light_gray_' + n.slice(7));
  // Wood: planks, logs, wood, stripped, leaves, saplings and shapes
  for (const w of Object.keys(WOODS).sort((a, b) => b.length - a.length)) {
    const c = WOODS[w];
    if (n === `stripped_${w}_log` || n === `stripped_${w}_wood` || n === `stripped_${w}_stem` || n === `stripped_${w}_hyphae`) return c.stripped;
    if (!n.startsWith(w + '_')) continue;
    const rest = n.slice(w.length + 1);
    if (rest === 'planks' || rest === 'mosaic') return c.planks;
    if (rest === 'log' || rest === 'wood' || rest === 'stem' || rest === 'hyphae' || rest === 'block') return c.log;
    if (rest === 'leaves') return c.leaves;
    if (rest === 'sapling' || rest === 'propagule') return c.leaves;
    if (SHAPES.some((s) => '_' + rest === s) || rest.startsWith('mosaic_')) return c.planks;
  }
  // Waxed copper and infested stone look like the plain block
  for (const prefix of ['waxed_', 'infested_', 'potted_'])
    if (n.startsWith(prefix)) {
      const c = lookup(n.slice(prefix.length));
      if (c !== undefined) return c;
    }
  // Coral: "tube_coral", "dead_brain_coral_fan"
  if (n.includes('coral')) {
    if (n.startsWith('dead_')) return 0x847c75;
    for (const kind of ['tube', 'brain', 'bubble', 'fire', 'horn']) if (n.startsWith(kind)) return BLOCKS[`${kind}_coral_block`];
  }
  // Shapes of stone-like materials: "stone_brick_stairs" → "stone_bricks"
  for (const s of SHAPES)
    if (n.endsWith(s)) {
      const base = n.slice(0, -s.length);
      for (const cand of [base, base + 's', base + '_block', base + '_planks', base.replace(/_tile$/, '_tiles')]) {
        const c = lookup(cand);
        if (c !== undefined) return c;
      }
    }
  // Ores in deepslate keep the ore's tint on a dark base
  if (n.startsWith('deepslate_') && n.endsWith('_ore')) return mix(BLOCKS.deepslate, BLOCKS[n.slice(10)] ?? BLOCKS.stone, 0.6);
  if (n.endsWith('_copper') || n.startsWith('cut_copper') || n.startsWith('chiseled_copper') || n.startsWith('copper_')) {
    for (const stage of ['oxidized', 'weathered', 'exposed']) if (n.includes(stage)) return BLOCKS[`${stage}_copper`];
    return BLOCKS.copper_block;
  }
  return undefined;
}

