const dicts: Record<string, Dict> = { zh, en };

function initialLang(): string {
  try {
    const saved = localStorage.getItem('spritestrack.lang');
    if (saved && dicts[saved]) return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let lang = initialLang();

export function t(key: string): string {
  return dicts[lang][key] ?? dicts.en[key] ?? key;
}

export function getLang(): string {
  return lang;
}

export function setLang(l: string): void {
  if (!dicts[l]) return;
  lang = l;
  try {
    localStorage.setItem('spritestrack.lang', l);
  } catch {
    /* ignore */
  }
}

/** Picks the current language from a `{ zh, en }` label (plugins may also pass a plain string). */
export function loc(l: Localized | undefined): string {
  if (!l) return '';
  return typeof l === 'string' ? l : lang === 'zh' ? l.zh : l.en;
}
